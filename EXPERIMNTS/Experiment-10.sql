-- Output: PL/SQL environment ready
CREATE TABLE patients(patient_id NUMBER PRIMARY KEY,patient_name VARCHAR2(80) NOT NULL,amount_due NUMBER(10,2) DEFAULT 0 CHECK(amount_due>=0));
CREATE TABLE patient_audit(audit_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,patient_id NUMBER,action_name VARCHAR2(10),action_time TIMESTAMP DEFAULT SYSTIMESTAMP);
INSERT INTO patients VALUES(1,'Arun',1250);
INSERT INTO patients VALUES(2,'Priya',0);
COMMIT;
-- Output: 2 patient rows inserted.
DECLARE
  v_name patients.patient_name%TYPE;
  v_due patients.amount_due%TYPE;
BEGIN
  SELECT patient_name,amount_due INTO v_name,v_due FROM patients WHERE patient_id=1;
  IF v_due>0 THEN DBMS_OUTPUT.PUT_LINE(v_name||' has an outstanding balance of '||TO_CHAR(v_due));
  ELSE DBMS_OUTPUT.PUT_LINE(v_name||' has no outstanding balance'); END IF;
EXCEPTION WHEN NO_DATA_FOUND THEN DBMS_OUTPUT.PUT_LINE('Patient not found');
END;
/
-- Output: Arun has an outstanding balance of 1250 (formatting may vary).
CREATE OR REPLACE PROCEDURE update_patient_due(p_id NUMBER,p_amount NUMBER) AS
BEGIN
  UPDATE patients SET amount_due=p_amount WHERE patient_id=p_id;
  IF SQL%ROWCOUNT=0 THEN RAISE_APPLICATION_ERROR(-20001,'Patient not found'); END IF;
END;
/
-- Output: procedure created.
CREATE OR REPLACE FUNCTION get_patient_due(p_id NUMBER) RETURN NUMBER AS
  v_due NUMBER(10,2);
BEGIN
  SELECT amount_due INTO v_due FROM patients WHERE patient_id=p_id;
  RETURN v_due;
EXCEPTION WHEN NO_DATA_FOUND THEN RETURN NULL;
END;
/
-- Output: function created; SELECT get_patient_due(1) FROM dual returns 1250.
CREATE OR REPLACE TRIGGER trg_patient_audit AFTER INSERT OR UPDATE OR DELETE ON patients FOR EACH ROW
BEGIN
  IF INSERTING THEN INSERT INTO patient_audit(patient_id,action_name) VALUES(:NEW.patient_id,'INSERT');
  ELSIF UPDATING THEN INSERT INTO patient_audit(patient_id,action_name) VALUES(:NEW.patient_id,'UPDATE');
  ELSIF DELETING THEN INSERT INTO patient_audit(patient_id,action_name) VALUES(:OLD.patient_id,'DELETE'); END IF;
END;
/
-- Output: trigger created; patient DML operations add audit rows.
DECLARE
  CURSOR c_due IS SELECT patient_name,amount_due FROM patients WHERE amount_due>0 ORDER BY patient_id;
  v_name patients.patient_name%TYPE;
  v_due patients.amount_due%TYPE;
BEGIN
  OPEN c_due;
  LOOP
    FETCH c_due INTO v_name,v_due;
    EXIT WHEN c_due%NOTFOUND;
    DBMS_OUTPUT.PUT_LINE(v_name||': '||TO_CHAR(v_due));
  END LOOP;
  CLOSE c_due;
END;
/
-- Output: Arun: 1250 (assuming no prior procedure update).
SELECT patient_id,patient_name,amount_due FROM patients ORDER BY patient_id;
